"""Generate the C rule tables from the data extracted from the game.

Reads islanders/data/extracted/{buildings,variants,packs,progression}.json and writes
  islanders/c/include/islanders_types.h  (type ids and table sizes)
  islanders/c/src/rules_data.c           (buildings, variants, interactions, packs, progression)
  islanders/c/gen/type_names.json        (exported object name -> type id, used by tools/islands_to_bin.py)

Run: python3 islanders/c/gen/gen_rules.py
"""
import json
import math
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]          # islanders/
DATA = ROOT / "data" / "extracted"
C = ROOT / "c"
U = 0.1757                                                  # building grid unit (world units)

B = {b["name"]: b for b in json.load(open(DATA / "buildings.json"))}
V = json.load(open(DATA / "variants.json"))
PACKS = json.load(open(DATA / "packs.json"))
PROG = json.load(open(DATA / "progression.json"))

MAX_VARIANTS, MAX_CELLS, MAX_PROBES, MAX_BOXES, MAX_RANGE_PTS = 8, 72, 40, 24, 2

# Nature objects that buildings react to. Every tree model except the Mighty Oak scores the same.
NATURE = {
    "Tree Cypress 02 a": "TREE", "Tree Oak 01 a": "TREE", "Tree Oak 01 b": "TREE", "Tree Oak 01 c": "TREE",
    "Tree Oak Mighty 01 a": "MIGHTY_OAK", "Flower Single 01 A": "FLOWER", "Flower": "FLOWER",
    "Gold Resource Field 01 a": "GOLD_VEIN",
}
NATURE_TYPES = ["TREE", "MIGHTY_OAK", "FLOWER", "GOLD_VEIN"]
SURF = {"Water": "ISL_S_WATER", "Terrain Sand": "ISL_S_SAND", "Terrain Grass": "ISL_S_GRASS",
        "Terrain Stone": "ISL_S_ROCK", "Wood Platform": "ISL_S_PLATEAU"}
TERRAIN_LAYERS = {"Terrain Grass", "Terrain Sand", "Terrain Stone"}
PLATEAU_TOP = {"Plateau": 0.2, "Water Plateau": 0.197, "Wall Plateau": 0.153}   # top above base (world units)

names = sorted(B)
ids = {n: i for i, n in enumerate(names)}
for k, t in enumerate(NATURE_TYPES):
    ids[t] = len(names) + k
n_types = len(names) + len(NATURE_TYPES)


def enum_name(n):
    return "ISL_T_" + re.sub(r"[^A-Z0-9]+", "_", n.upper()).strip("_")


def type_of(name):
    return ids[NATURE.get(name, name)]


def mask(layers):
    return " | ".join(f"(1u << {SURF[s]})" for s in layers if s in SURF) or "0"


def coverage(boxes, ofx, ofz, dx, dz, n=6):
    """Fraction of grid cell (dx, dz) covered by the union of boxes, with the pivot shifted by (ofx, ofz)."""
    hit = 0
    for i in range(n):
        for j in range(n):
            x = (dx - 0.5 + (i + 0.5) / n) * U + ofx
            z = (dz - 0.5 + (j + 0.5) / n) * U + ofz
            hit += any(b[0][0] <= x <= b[1][0] and b[0][2] <= z <= b[1][2] for b in boxes)
    return hit / (n * n)


def raster(variant):
    """Footprint of a variant on the grid. Picks a half-cell pivot shift per axis so the boxes line up
    with grid lines, then keeps cells at least half covered. Returns (cells, (ofx, ofz))."""
    boxes = variant["boxes"]
    if not boxes:
        return [(0, 0)], (0.0, 0.0)
    lo_x, hi_x = min(b[0][0] for b in boxes), max(b[1][0] for b in boxes)
    lo_z, hi_z = min(b[0][2] for b in boxes), max(b[1][2] for b in boxes)
    best = None
    for ofx in (0.0, U / 2):
        for ofz in (0.0, U / 2):
            cov = {}
            for dx in range(math.floor((lo_x - ofx) / U) - 1, math.ceil((hi_x - ofx) / U) + 2):
                for dz in range(math.floor((lo_z - ofz) / U) - 1, math.ceil((hi_z - ofz) / U) + 2):
                    f = coverage(boxes, ofx, ofz, dx, dz)
                    if f > 0:
                        cov[(dx, dz)] = f
            ambiguity = sum(min(f, 1 - f) for f in cov.values())
            cells = sorted(c for c, f in cov.items() if f >= 0.5) or [min(cov, key=lambda c: abs(c[0]) + abs(c[1]))]
            if best is None or ambiguity < best[0] - 1e-9:
                best = (ambiguity, cells, (ofx, ofz))
    return best[1], best[2]


def probe_cells(variant, off):
    pts = {(round((p[0] - off[0]) / U), round((p[2] - off[1]) / U)) for p in variant["probes"]}
    return sorted(pts) or [(0, 0)]


out = ['/* Generated by gen/gen_rules.py from the game\'s extracted data. Do not edit by hand. */',
       '#include "islanders.h"\n', "const isl_def ISL_DEFS[ISL_N_TYPES] = {"]
for n in names:
    b = B[n]
    vs = V.get(n, [])[:MAX_VARIANTS] or [{"boxes": [], "probes": [], "height": 0.2}]
    gate_name, gate_amount = b["requires"]
    rp = [(o["x"], o["y"], o["z"]) for o in b["rangeOffsets"]][:MAX_RANGE_PTS] or [(0.0, 0.0, 0.0)]
    vtxt = []
    for v in vs:
        cells, off = raster(v)
        cells = cells[:MAX_CELLS]
        probes = probe_cells(v, off)[:MAX_PROBES]
        boxes = v["boxes"][:MAX_BOXES]
        vtxt.append(
            "{ " + f"{{{off[0]:.5f}f, {off[1]:.5f}f}}, {len(cells)}, {{ " + ", ".join(f"{{{dx},{dz}}}" for dx, dz in cells) + " }, "
            + f"{len(probes)}, {{ " + ", ".join(f"{{{dx},{dz}}}" for dx, dz in probes) + " }, "
            + f"{len(boxes)}, {{ " + ", ".join("{" + ",".join(f"{x:.4f}f" for x in a + c) + "}" for a, c in boxes) + " } }")
    out.append(
        f'    {{ "{n}", {b["base"]}, {b["snowBonus"]}, {b["range"]:.4f}f, '
        f'{len(rp)}, {{ ' + ", ".join(f"{{{x:.3f}f,{y:.3f}f,{z:.3f}f}}" for x, y, z in rp) + " }, "
        f'{mask(b["surface"])}, {mask(b["groundedBreakers"])}, '
        f'{int(b["steepOK"])}, {int(not (TERRAIN_LAYERS & set(b["forbiddenOverlap"])))}, '
        f'{int(n in PLATEAU_TOP)}, {PLATEAU_TOP.get(n, 0.0):.3f}f, {int(b["onWall"])}, '
        f'{b["amount"]}, {b["amountWater"]}, {b["perUnlockWater"]:.3f}f, '
        f'{ids[gate_name] if gate_name else -1}, {gate_amount:.3f}f, {int(b["reAddDeck"])}, '
        f'{len(vs)}, {{ ' + ", ".join(vtxt) + " } },")
for t in NATURE_TYPES:
    out.append(f'    {{ "{t.title().replace("_", " ")}" }},')
out.append("};\n")

W = [[0] * n_types for _ in range(n_types)]
for n in names:
    for other, s in B[n]["interactions"]:
        j = type_of(other)
        if W[ids[n]][j] == 0:
            W[ids[n]][j] = s
out.append("const int16_t ISL_W[ISL_N_TYPES][ISL_N_TYPES] = {")
out += ["    { " + ", ".join(map(str, row)) + " }," for row in W]
out.append("};\n")

SPECIAL = {17350: "ISL_PACK_WATER_PLATEAU", 17349: "ISL_PACK_WALL_PLATEAU", 17348: "ISL_PACK_STATUE"}
SEASON = {0: "ISL_SEASON_WINTER", 1: "ISL_SEASON_SUMMER", 2: "ISL_SEASON_BOTH"}
regular = [p for p in PACKS if p["pid"] not in SPECIAL]
special = sorted([p for p in PACKS if p["pid"] in SPECIAL], key=lambda p: SPECIAL[p["pid"]])
order = regular + special
special_index = {SPECIAL[p["pid"]]: len(regular) + k for k, p in enumerate(special)}


def ilist(xs, n):
    xs = list(xs) + [0] * (n - len(xs))
    return "{ " + ", ".join(map(str, xs)) + " }"


out.append("const isl_pack ISL_PACKS[ISL_N_PACKS] = {")
for p in order:
    bs = [ids[x] for x in p["buildings"]]
    rq = [ids[x] for x in p["requirements"]]
    out.append(
        f'    {{ "{" + ".join(p["buildings"])}", {len(bs)}, {ilist(bs, 4)}, {len(rq)}, {ilist(rq, 8)}, {p["jokers"]}, '
        f'{p["minUnlocks"]}, {int(p["grass"])}, {int(p["sand"])}, {int(p["noSand"])}, {int(p["rock"])}, '
        f'{int(p["wood"])}, {int(p["gold"])}, {SEASON[p["availableIn"]]}, {int(p["alwaysShow"])} }},')
out.append("};\n")
inc, goals = PROG["pack_score_increments"], PROG["island_goals"]
out.append(f"const int ISL_PACK_INC[ISL_N_PACK_INC] = {{ {', '.join(map(str, inc))} }};")
out.append(f"const int ISL_ISLAND_GOALS[ISL_N_ISLAND_GOALS] = {{ {', '.join(map(str, goals))} }};")
(C / "src").mkdir(exist_ok=True)
(C / "src" / "rules_data.c").write_text("\n".join(out) + "\n")

h = ["/* Generated by gen/gen_rules.py. Do not edit by hand. */", "#ifndef ISLANDERS_TYPES_H", "#define ISLANDERS_TYPES_H", "", "enum {"]
h += [f"    {enum_name(n)} = {ids[n]}," for n in names]
h += [f"    ISL_T_{t} = {ids[t]}," for t in NATURE_TYPES]
h += ["};", "",
      f"#define ISL_N_BUILDINGS {len(names)}", f"#define ISL_N_TYPES {n_types}",
      f"#define ISL_N_PACKS {len(order)}", f"#define ISL_N_REGULAR_PACKS {len(regular)}"]
h += [f"#define {k} {v}" for k, v in special_index.items()]
h += [f"#define ISL_N_PACK_INC {len(inc)}", f"#define ISL_INC_AFTER_LIST {PROG['increase_after_list_per_pack']}",
      f"#define ISL_N_ISLAND_GOALS {len(goals)}", f"#define ISL_TRAVEL_BONUS {PROG['next_island_bonus']}",
      f"#define ISL_MAX_VARIANTS {MAX_VARIANTS}", f"#define ISL_MAX_CELLS {MAX_CELLS}", f"#define ISL_MAX_PROBES {MAX_PROBES}",
      f"#define ISL_MAX_BOXES {MAX_BOXES}", f"#define ISL_MAX_RANGE_PTS {MAX_RANGE_PTS}",
      f"#define ISL_CELL {U}f", "", "#endif"]
(C / "include").mkdir(exist_ok=True)
(C / "include" / "islanders_types.h").write_text("\n".join(h) + "\n")

json.dump({**{n: ids[n] for n in names}, **{k: ids[v] for k, v in NATURE.items()}},
          open(C / "gen" / "type_names.json", "w"), indent=1)
print(f"{len(names)} buildings, {n_types} types, {len(order)} packs")
for n in names:
    vs = V.get(n, [])
    def desc(v):
        cells, off = raster(v)
        xs = [c[0] for c in cells]; zs = [c[1] for c in cells]
        return f"{max(xs)-min(xs)+1}x{max(zs)-min(zs)+1} ({len(cells)} cells)"
    print(f"  {n:<15} " + "; ".join(desc(v) for v in vs[:MAX_VARIANTS]))
